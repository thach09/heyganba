"""Generate the reviewed V17 cleanup migration from a captured database snapshot.

The CSV is exported from the isolated production-profile rehearsal database.  The
checked-in manifest is the durable record; normal regeneration reads that
manifest and does not require database access.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / "docs/Content/optional-fields-clearance-2026-10-20.json"
RELEASE_SQL = ROOT / "backend/src/main/resources/db/migration-release/V17__clear_unverified_vocabulary_optional_fields.sql"
STAGING_SQL = ROOT / "backend/src/main/resources/db/migration-staging/V17__clear_unverified_vocabulary_optional_fields.sql"
OPTIONAL_COLUMNS = (
    "han_viet",
    "sino_vietnamese",
    "example_zh",
    "example_sentence",
    "example_pinyin",
    "example_reading",
    "example_vi",
    "example_meaning",
)


def digest(row: dict[str, str]) -> str:
    values = [
        row["word"],
        row["pinyin"] or row["reading"],
        row["meaning_vi"] or row["meaning"],
        row["han_viet"] or row["sino_vietnamese"],
        row["example_zh"] or row["example_sentence"],
        row["example_pinyin"] or row["example_reading"],
        row["example_vi"] or row["example_meaning"],
        row["hsk_level"],
        row["part_of_speech"],
    ]
    framed = "".join(f"{len(value)}:{value}" for value in values)
    return hashlib.sha256(framed.encode("utf-8")).hexdigest()


def manifest_from_csv(path: Path) -> dict:
    raw = path.read_bytes()
    with path.open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    versions = {}
    for row in rows:
        versions.setdefault((row["curriculum_version"], row["review_status"]), 0)
        versions[(row["curriculum_version"], row["review_status"])] += 1
    assert versions == {
        ("INTERNAL_SIX_LEVEL_SELECTION_V9", "APPROVED"): 491,
        ("INTERNAL_SIX_LEVEL_SELECTION_V9", "PENDING_REVIEW"): 69,
        ("INTERNAL_WEB_SUPPLEMENT_2026_10_20", "APPROVED"): 24,
    }, f"Unexpected clearance source population: {versions}"
    records = []
    for row in rows:
        before = digest(row)
        cleared = dict(row)
        for column in OPTIONAL_COLUMNS:
            cleared[column] = ""
        after = digest(cleared)
        status = row["review_status"]
        stored = row["provenance_content_sha256"] or None
        if status == "APPROVED":
            assert stored == before, f"Stored provenance digest mismatch for vocabulary ID {row['id']}"
        else:
            assert status == "PENDING_REVIEW" and stored is None, f"Unexpected review state/digest for ID {row['id']}"
        records.append({
            "id": int(row["id"]),
            "curriculumVersion": row["curriculum_version"],
            "reviewStatus": status,
            "word": row["word"],
            "pinyin": row["pinyin"] or row["reading"],
            "beforeDigest": before,
            "afterDigest": after,
            "initialProvenanceDigest": stored,
        })
    return {
        "schemaVersion": 1,
        "purpose": "Withdraw unpublished Hán Việt and example fields; normalize blank optional fields to SQL NULL.",
        "sourceSnapshot": {
            "database": "heyganba_cont_20261020_fresh (isolated PostgreSQL 16, production profile)",
            "rowCount": len(rows),
            "csvSha256": hashlib.sha256(raw).hexdigest(),
        },
        "records": records,
    }


def migration_sql(manifest: dict) -> str:
    encoded = json.dumps(manifest["records"], ensure_ascii=False, separators=(",", ":"))
    return f"""-- Generated by scripts/generate-optional-field-clearance-migration.py.
-- Source evidence: docs/Content/optional-fields-clearance-2026-10-20.json.
-- This migration withdraws optional fields with no publishable evidence and
-- refreshes approved content digests without changing lexical review status.
CREATE FUNCTION pg_temp.review_content_digest(v vocabulary) RETURNS text
LANGUAGE sql IMMUTABLE AS $digest$
 SELECT encode(sha256(convert_to(length(COALESCE(word,''))::text || ':' || COALESCE(word,'') || length(COALESCE(COALESCE(pinyin,reading),''))::text || ':' || COALESCE(COALESCE(pinyin,reading),'') || length(COALESCE(COALESCE(meaning_vi,meaning),''))::text || ':' || COALESCE(COALESCE(meaning_vi,meaning),'') || length(COALESCE(COALESCE(han_viet,sino_vietnamese),''))::text || ':' || COALESCE(COALESCE(han_viet,sino_vietnamese),'') || length(COALESCE(COALESCE(example_zh,example_sentence),''))::text || ':' || COALESCE(COALESCE(example_zh,example_sentence),'') || length(COALESCE(COALESCE(example_pinyin,example_reading),''))::text || ':' || COALESCE(COALESCE(example_pinyin,example_reading),'') || length(COALESCE(COALESCE(example_vi,example_meaning),''))::text || ':' || COALESCE(COALESCE(example_vi,example_meaning),'') || length(COALESCE(hsk_level::text,''))::text || ':' || COALESCE(hsk_level::text,'') || length(COALESCE(part_of_speech,''))::text || ':' || COALESCE(part_of_speech,''), 'UTF8')), 'hex') FROM (SELECT (v).*) fields
$digest$;

DO $cleanup$
DECLARE
    item jsonb;
    current_row vocabulary%ROWTYPE;
    actual_digest text;
    expected_provenance text;
    manifest_count integer := 0;
    target_ids bigint[] := ARRAY[]::bigint[];
    target_id bigint;
BEGIN
    -- The manifest owns exactly these identities. Later batches may legitimately
    -- use the same curriculum version and must remain outside this withdrawal.
    FOR item IN
        SELECT value FROM jsonb_array_elements($clear_manifest${encoded}$clear_manifest$::jsonb)
    LOOP
        manifest_count := manifest_count + 1;
        IF item->>'curriculumVersion' = 'INTERNAL_SIX_LEVEL_SELECTION_V9' THEN
            SELECT v.* INTO STRICT current_row FROM vocabulary v WHERE v.id=(item->>'id')::bigint;
        ELSE
            -- Supplement IDs are sequence-generated and may shift when an
            -- earlier rehearsal inserted then removed rows. Their lexical
            -- identities are unique within this published supplement.
            SELECT v.* INTO STRICT current_row FROM vocabulary v
            WHERE v.curriculum_version=item->>'curriculumVersion'
              AND v.review_status::text=item->>'reviewStatus'
              AND v.word=item->>'word'
              AND COALESCE(v.pinyin, v.reading, '')=item->>'pinyin';
        END IF;
        target_id := current_row.id;
        IF target_id = ANY(target_ids) THEN
            RAISE EXCEPTION 'Clearance manifest resolves duplicate vocabulary ID %', target_id;
        END IF;
        target_ids := array_append(target_ids, target_id);

        IF current_row.curriculum_version IS DISTINCT FROM item->>'curriculumVersion'
           OR current_row.review_status IS DISTINCT FROM item->>'reviewStatus'
           OR current_row.word IS DISTINCT FROM item->>'word'
           OR COALESCE(current_row.pinyin, current_row.reading, '') IS DISTINCT FROM item->>'pinyin' THEN
            RAISE EXCEPTION 'Vocabulary identity/status changed for ID %', item->>'id';
        END IF;
        IF current_row.han_viet_verified OR current_row.example_verified
           OR current_row.han_viet_source_ref IS NOT NULL OR current_row.example_source_ref IS NOT NULL THEN
            RAISE EXCEPTION 'Optional fields have verification evidence for ID %; refusing withdrawal', item->>'id';
        END IF;

        actual_digest := pg_temp.review_content_digest(current_row);
        IF actual_digest NOT IN (item->>'beforeDigest', item->>'afterDigest') THEN
            RAISE EXCEPTION 'Unexpected current content digest for ID %', item->>'id';
        END IF;

        IF current_row.review_status = 'APPROVED' THEN
            expected_provenance := CASE WHEN actual_digest = item->>'beforeDigest'
                                        THEN item->>'beforeDigest' ELSE item->>'afterDigest' END;
            IF current_row.provenance_content_sha256 IS DISTINCT FROM expected_provenance THEN
                RAISE EXCEPTION 'Approved provenance digest mismatch for ID %', item->>'id';
            END IF;
        ELSIF current_row.provenance_content_sha256 IS NOT NULL THEN
            RAISE EXCEPTION 'Pending vocabulary unexpectedly has a provenance digest for ID %', item->>'id';
        END IF;

        UPDATE vocabulary
        SET han_viet=NULL, sino_vietnamese=NULL,
            example_zh=NULL, example_sentence=NULL,
            example_pinyin=NULL, example_reading=NULL,
            example_vi=NULL, example_meaning=NULL,
            han_viet_verified=false, example_verified=false,
            provenance_content_sha256=CASE WHEN review_status='APPROVED'
                THEN item->>'afterDigest' ELSE NULL END
        WHERE id=target_id;

        SELECT v.* INTO STRICT current_row FROM vocabulary v WHERE v.id=target_id;
        actual_digest := pg_temp.review_content_digest(current_row);
        IF actual_digest <> item->>'afterDigest'
           OR current_row.han_viet IS NOT NULL OR current_row.sino_vietnamese IS NOT NULL
           OR current_row.example_zh IS NOT NULL OR current_row.example_sentence IS NOT NULL
           OR current_row.example_pinyin IS NOT NULL OR current_row.example_reading IS NOT NULL
           OR current_row.example_vi IS NOT NULL OR current_row.example_meaning IS NOT NULL THEN
            RAISE EXCEPTION 'Optional-field cleanup verification failed for ID %', item->>'id';
        END IF;
        IF current_row.review_status = 'APPROVED'
           AND current_row.provenance_content_sha256 IS DISTINCT FROM actual_digest THEN
            RAISE EXCEPTION 'Refreshed provenance digest mismatch for ID %', item->>'id';
        END IF;
    END LOOP;

    IF manifest_count <> {manifest['sourceSnapshot']['rowCount']} THEN
        RAISE EXCEPTION 'Clearance manifest row count changed: expected %, got %', {manifest['sourceSnapshot']['rowCount']}, manifest_count;
    END IF;
    IF EXISTS (
        SELECT 1 FROM vocabulary
        WHERE id = ANY(target_ids)
          AND (han_viet IS NOT NULL OR sino_vietnamese IS NOT NULL
               OR example_zh IS NOT NULL OR example_sentence IS NOT NULL
               OR example_pinyin IS NOT NULL OR example_reading IS NOT NULL
               OR example_vi IS NOT NULL OR example_meaning IS NOT NULL)
    ) THEN
        RAISE EXCEPTION 'Unpublished optional vocabulary content remains after V17';
    END IF;
END
$cleanup$;
DROP FUNCTION pg_temp.review_content_digest(vocabulary);
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-csv", type=Path, help="capture source CSV from the isolated rehearsal DB")
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    args = parser.parse_args()

    if args.source_csv:
        manifest = manifest_from_csv(args.source_csv)
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    else:
        manifest = json.loads(args.manifest.read_text(encoding="utf-8"))

    rows = manifest["records"]
    assert len(rows) == manifest["sourceSnapshot"]["rowCount"]
    assert [row["id"] for row in rows] == sorted({row["id"] for row in rows})
    sql = migration_sql(manifest)
    RELEASE_SQL.parent.mkdir(parents=True, exist_ok=True)
    STAGING_SQL.parent.mkdir(parents=True, exist_ok=True)
    RELEASE_SQL.write_text(sql, encoding="utf-8", newline="\n")
    STAGING_SQL.write_bytes(RELEASE_SQL.read_bytes())
    print(json.dumps({
        "manifest": str(args.manifest.relative_to(ROOT)),
        "records": len(rows),
        "releaseSql": str(RELEASE_SQL.relative_to(ROOT)),
        "sha256": hashlib.sha256(RELEASE_SQL.read_bytes()).hexdigest(),
    }, indent=2))


if __name__ == "__main__":
    main()
